import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
const browser=await chromium.connectOverCDP('http://127.0.0.1:9223');
const context=browser.contexts()[0];const page=context.pages().find(p=>p.url().includes('tauri.localhost'))||context.pages()[0];
if(!page)throw Error('FLUX WebView not found');
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.waitForSelector('#root',{timeout:60000});
await page.evaluate(()=>{localStorage.setItem('flux.onboarded','true');location.hash='#/';});
await page.reload();
await page.locator('.stream-card').first().waitFor({timeout:60000});
await fs.mkdir('artifacts/qa',{recursive:true});
await page.screenshot({path:'artifacts/qa/windows-home.png',fullPage:false});
await page.locator('.stream-card').first().click();
await page.waitForFunction(()=>document.querySelector('video')?.readyState>=2,{},{timeout:60000});
await page.evaluate(()=>{const video=document.querySelector('video');video.muted=true;return video.play();});
await page.waitForFunction(()=>document.querySelector('video')?.currentTime>2,{},{timeout:30000});
await page.screenshot({path:'artifacts/qa/windows-player.png',fullPage:false});
await page.getByRole('button',{name:'Réduire le lecteur'}).click();
await page.locator('.player-shell.mini').waitFor();
await page.getByRole('button',{name:'Fermer le lecteur'}).click();
await fs.writeFile('artifacts/qa/windows-smoke.json',JSON.stringify({catalog:true,videoPlayback:true,miniPlayer:true,errors},null,2));
await browser.close();
if(errors.length)throw Error(JSON.stringify(errors));
console.log('Windows native catalog, playback and mini-player verified.');
